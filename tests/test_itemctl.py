"""items_control.txt GUI section (gui/rozgui/itemctl.py) and the market scanner keeping it."""
from __future__ import annotations

import importlib.util
import os
import tempfile
import unittest

import support
from rozgui import itemctl as I
from rozgui.tradetab import NPC_RE, npc_value

SCANNER = os.path.join(support.REPO_ROOT, 'tools', 'market_scanner', 'rozclub_market_scanner.py')

MARKET_FILE = """# Auto-generated by ROZCLUB Market Scanner
[Not For Sale] Novice Fly Wing 1000 0 0
12323 1000 0 0
Red Potion 10 1 0
501 10 1 0
Jellopy 0 0 1
909 0 0 1
all 0 1 0
"""


class ItemCtlTest(unittest.TestCase):
    def setUp(self) -> None:
        self.dir = tempfile.mkdtemp()
        with open(I.path_for(self.dir), 'w', encoding='utf-8') as f:
            f.write(MARKET_FILE)

    def _text(self) -> str:
        with open(I.path_for(self.dir), encoding='utf-8') as f:
            return f.read()

    def test_lookup_follows_openkore_order(self) -> None:
        v = I.file_values(self.dir)
        self.assertEqual(I.lookup(v, 12323, ['[Not For Sale] Novice Fly Wing']), (1000, 0, 0))
        self.assertEqual(I.lookup(v, 501, ['Red Potion']), (10, 1, 0))
        self.assertEqual(I.lookup(v, 99999, ['Nothing']), (0, 1, 0))          # falls back to `all`

    def test_save_and_load_round_trip(self) -> None:
        ic = I.ItemCtl(default=I.SELL)
        ic.rules[501] = I.ItemRule(501, 'Red Potion', I.KEEP)
        ic.rules[7033] = I.ItemRule(7033, 'Poison Spore', I.STORE, 5)
        I.save(self.dir, ic, {501: ['Red Potion'], 7033: ['Poison Spore']})
        back = I.load(self.dir)
        self.assertEqual(back.default, I.SELL)
        self.assertEqual({k: (r.action, r.keep) for k, r in back.rules.items()},
                         {501: (I.KEEP, 0), 7033: (I.STORE, 5)})
        text = self._text()
        self.assertTrue(text.startswith('# Auto-generated'), 'the rest of the file is kept')
        self.assertIn('Red Potion 0 0 0', text)                                # name line beats a market name line
        I.save(self.dir, back, {501: ['Red Potion'], 7033: ['Poison Spore']})
        self.assertEqual(self._text().count(I.END), 1, 'saving twice keeps one section')

    def test_name_keys_openkore_could_misread_are_skipped_or_quoted(self) -> None:
        ic = I.ItemCtl()
        ic.rules[4001] = I.ItemRule(4001, 'x', I.STORE)
        lines = I.build_block(ic, {4001: ['Unknown #4001', 'Thing 2', '#bad', '2nd Thing']})
        self.assertIn('"Thing 2" 0 1 0', lines)
        self.assertFalse(any(l.startswith(('Unknown', '#bad', '2nd')) for l in lines))

    def test_scanner_keeps_the_gui_section(self) -> None:
        spec = importlib.util.spec_from_file_location('rozclub_market_scanner', SCANNER)
        assert spec and spec.loader
        scanner = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(scanner)
        ic = I.ItemCtl()
        ic.rules[501] = I.ItemRule(501, 'Red Potion', I.SELL, 5)
        I.save(self.dir, ic, {501: ['Red Potion']})
        drops = [{'id': 909, 'name': 'Jellopy', 'min_str': '1', 'avg_str': '1', 'count': 1, 'min_val': 1}]
        scanner.update_openkore_items_control(drops, 1000, I.path_for(self.dir))
        text = self._text()
        self.assertIn('Auto-generated by ROZCLUB Market Scanner (Min Store Price', text)
        self.assertTrue(text.rstrip().endswith(I.END), 'GUI section stays last')
        self.assertEqual(I.load(self.dir).rules[501].keep, 5)


class NpcValueTest(unittest.TestCase):
    def test_npc_value(self) -> None:
        self.assertEqual(npc_value('Kafra Employee — payon 181 104'), 'payon 181 104')
        self.assertEqual(npc_value('payon 159 96'), 'payon 159 96')
        self.assertTrue(NPC_RE.match('payon 181 104'))
        self.assertFalse(NPC_RE.match('payon 1 2 3'))


if __name__ == '__main__':
    unittest.main()
